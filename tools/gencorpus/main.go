// Command gencorpus writes the conformance corpus: conformance/manifest.json
// and the committed vector files in conformance/vectors/small.
//
// The expected outcome of every vector is written down here from the rules of
// spec/SPEC.md, never obtained by running the library under test. The Go test
// conformance_test.go then checks the library against these expectations.
//
// Usage: go run ./tools/gencorpus [-root dir] [-large-dir dir]
//
// With -large-dir the generated "large" inputs are also written to files, as
// they are shipped in the release tarball for other languages.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"

	"github.com/FelixMiddelhoff/spillgate/internal/corpus"
)

const corpusVersion = "0.1.0"

func main() {
	root := flag.String("root", ".", "repository root")
	largeDir := flag.String("large-dir", "", "also write the large generated inputs to this directory")
	flag.Parse()

	b := &builder{files: map[string][]byte{}, large: map[string][]byte{}, counters: map[string]int{}}
	defineVectors(b)
	if err := b.check(); err != nil {
		fmt.Fprintln(os.Stderr, "gencorpus:", err)
		os.Exit(1)
	}

	if err := b.write(*root, *largeDir); err != nil {
		fmt.Fprintln(os.Stderr, "gencorpus:", err)
		os.Exit(1)
	}
	fmt.Printf("wrote %d vectors (%d small files, %d large generated)\n", len(b.vectors), len(b.files), len(b.large))
}

// The structs mirror conformance/SCHEMA.md; field order is the order in the
// written JSON.

type vector struct {
	ID          string         `json:"id"`
	Description string         `json:"description"`
	Rules       []string       `json:"rules"`
	Refs        []string       `json:"refs,omitempty"`
	Tags        []string       `json:"tags,omitempty"`
	Tier        string         `json:"tier"`
	Encodings   []string       `json:"encodings"`
	Input       input          `json:"input"`
	Limits      map[string]any `json:"limits"`
	ReadPattern []int          `json:"read_pattern,omitempty"`
	Options     map[string]any `json:"options,omitempty"`
	Expect      expect         `json:"expect"`
}

type input struct {
	File      string       `json:"file,omitempty"`
	Generator *corpus.Spec `json:"generator,omitempty"`
	SHA256    string       `json:"sha256"`
}

type expect struct {
	Outcome          string `json:"outcome"`
	Length           *int64 `json:"length,omitempty"`
	SHA256           string `json:"sha256,omitempty"`
	Phase            string `json:"phase,omitempty"`
	DeliveredAtMost  *int64 `json:"delivered_at_most,omitempty"`
	DeliveredExactly *int64 `json:"delivered_exactly,omitempty"`
	Layer            int    `json:"layer,omitempty"`
}

type manifest struct {
	SchemaVersion int      `json:"schema_version"`
	CorpusVersion string   `json:"corpus_version"`
	Vectors       []vector `json:"vectors"`
}

// builder collects vectors and the files that go with them.
type builder struct {
	vectors  []vector
	files    map[string][]byte // path relative to conformance/ -> bytes (small tier)
	large    map[string][]byte // vector id -> generated bytes (large tier, for -large-dir)
	counters map[string]int
}

// nonNil makes sure a missing list is written as [] and not as null.
func nonNil(list []string) []string {
	if list == nil {
		return []string{}
	}
	return list
}

// nextID returns the next ID of a family, for example SG-V-BND-0007.
func (b *builder) nextID(family string) string {
	b.counters[family]++
	return fmt.Sprintf("SG-V-%s-%04d", family, b.counters[family])
}

// addFile adds a small vector whose input is the given bytes, stored as a file.
func (b *builder) addFile(family string, v vector, stream []byte) {
	v.ID = b.nextID(family)
	v.Tier = "small"
	v.Encodings = nonNil(v.Encodings)
	path := "vectors/small/" + v.ID + ".bin"
	b.files[path] = stream
	v.Input = input{File: path, SHA256: corpus.SHA256Hex(stream)}
	b.vectors = append(b.vectors, v)
}

// addGenerated adds a vector whose input is described by a generator spec.
// tier is "small" for cheap specs and "large" for GiB-scale decoded bombs.
func (b *builder) addGenerated(family, tier string, v vector, spec corpus.Spec) {
	v.ID = b.nextID(family)
	v.Tier = tier
	v.Encodings = nonNil(v.Encodings)
	stream, err := corpus.Generate(spec)
	if err != nil {
		panic(err)
	}
	v.Input = input{Generator: &spec, SHA256: corpus.SHA256Hex(stream)}
	if tier == "large" {
		b.large[v.ID] = stream
	}
	b.vectors = append(b.vectors, v)
}

// check rejects vectors that break the manifest rules before anything is written.
func (b *builder) check() error {
	seen := map[string]bool{}
	for _, v := range b.vectors {
		switch {
		case seen[v.ID]:
			return fmt.Errorf("duplicate id %s", v.ID)
		case len(v.Rules) == 0:
			return fmt.Errorf("%s names no rule", v.ID)
		case v.Description == "":
			return fmt.Errorf("%s has no description", v.ID)
		case v.Expect.Outcome == "":
			return fmt.Errorf("%s has no expected outcome", v.ID)
		}
		seen[v.ID] = true
	}
	return nil
}

func (b *builder) write(root, largeDir string) error {
	sort.Slice(b.vectors, func(i, j int) bool { return b.vectors[i].ID < b.vectors[j].ID })

	conformance := filepath.Join(root, "conformance")
	if err := os.RemoveAll(filepath.Join(conformance, "vectors", "small")); err != nil {
		return err
	}
	for path, data := range b.files {
		full := filepath.Join(conformance, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(full, data, 0o644); err != nil {
			return err
		}
	}
	if largeDir != "" {
		if err := os.MkdirAll(largeDir, 0o755); err != nil {
			return err
		}
		for id, data := range b.large {
			if err := os.WriteFile(filepath.Join(largeDir, id+".bin"), data, 0o644); err != nil {
				return err
			}
		}
	}

	out, err := json.MarshalIndent(manifest{SchemaVersion: 1, CorpusVersion: corpusVersion, Vectors: b.vectors}, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(conformance, "manifest.json"), append(out, '\n'), 0o644)
}
